    pdf.info_row('Peak Output', f"{results['peak_power_kw']:.1f}", "kW")
    pdf.info_row('Specific Yield', f"{results['specific_yield']:.0f}", "kWh/kWp/year")
    
    # Disclaimer
    pdf.ln(10)
    pdf.set_font(pdf.ufont_italic, '', 8)
    pdf.set_text_color(150, 150, 150)
