    hourly = results['hourly_output'].iloc[:168]  # First week
    
    fig, ax = plt.subplots(figsize=(width / 100, height / 100), dpi=100)
    fig.patch.set_facecolor('#ffffff')
    ax.set_facecolor('#fafbfc')
    
    ax.plot(range(len(hourly)), hourly.values, color='#3b82f6', linewidth=1.2, alpha=0.9)
    ax.fill_between(range(len(hourly)), hourly.values, alpha=0.15, color='#3b82f6')
    
    ax.set_xlabel('Hour', fontsize=9, color='#374151')
